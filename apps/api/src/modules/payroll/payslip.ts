const locale = (language: 'en' | 'bn') => (language === 'bn' ? 'bn-BD' : 'en-GB');

export const date = (language: 'en' | 'bn', iso: string) =>
  new Intl.DateTimeFormat(locale(language), {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${iso}T00:00:00Z`));

/** "October 2026" / "অক্টোবর ২০২৬" for a whole month, else the dates. */
export function periodName(language: 'en' | 'bn', start: string, end: string): string {
  const first = new Date(`${start}T00:00:00Z`);
  const wholeMonth =
    start.endsWith('-01') &&
    new Date(Date.UTC(first.getUTCFullYear(), first.getUTCMonth() + 1, 0))
      .toISOString()
      .slice(0, 10) === end;
  return wholeMonth
    ? new Intl.DateTimeFormat(locale(language), {
        month: 'long',
        year: 'numeric',
        timeZone: 'UTC',
      }).format(first)
    : `${date(language, start)} – ${date(language, end)}`;
}

/** Money in the language's digits, with paisa only when there are any. */
export const amountText = (language: 'en' | 'bn', amount: string) =>
  new Intl.NumberFormat(locale(language), {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(Number(amount));

const number = (language: 'en' | 'bn', n: number) =>
  new Intl.NumberFormat(locale(language), { maximumFractionDigits: 2 }).format(n);

/** A payslip as a printable A4 page in English or Bangla. */
export function payslipHtml(data: PayslipData): string {
  const l = LABELS[data.language];
  const name = (line: PayLineView) =>
    data.language === 'bn' && line.nameBn ? line.nameBn : line.name;
  const rows = (kind: PayLineView['kind']) =>
    data.lines
      .filter((line) => line.kind === kind)
      .map(
        (line) =>
          `<tr><td>${escapeHtml(name(line))}</td><td class="num">${amountText(data.language, line.amount)}</td></tr>`,
      )
      .join('');
  const v = data.variables;
  const words = Number(data.net) >= 0 ? takaInWords(data.net, data.language) : '';
  const css = `
@page{size:A4;margin:14mm 16mm}
.head{border-bottom:2px solid #15803d;padding-bottom:6px;margin-bottom:12px;display:flex;justify-content:space-between;align-items:flex-end}
.company{font-size:14pt;font-weight:700}
.details{font-size:8.5pt;color:#4b5563}
.title{font-size:13pt;font-weight:700;text-align:right}
.grid{display:grid;grid-template-columns:1fr 1fr;gap:4px 24px;font-size:9.5pt;margin-bottom:12px}
.grid span{color:#4b5563}
.days{margin-bottom:12px}
.days td,.days th{text-align:center}
.cols{display:grid;grid-template-columns:1fr 1fr;gap:16px}
.num{text-align:right;font-variant-numeric:tabular-nums}
tfoot td{font-weight:700;background:#f9fafb}
.net{margin-top:14px;border:2px solid #15803d;border-radius:6px;padding:8px 12px;display:flex;justify-content:space-between;font-size:12pt;font-weight:700}
.words{margin-top:6px;font-size:9.5pt}
.note{margin-top:18px;font-size:8pt;color:#6b7280}`;
  return page(
    data.language,
    css,
    `<div class="head"><div><div class="company">${escapeHtml(data.company.name)}</div>
<div class="details">${escapeHtml(data.company.details)}</div></div>
<div class="title">${data.kind === 'settlement' ? l.settlement : data.kind === 'wppf' ? l.wppf : data.kind === 'bonus' ? l.bonus : data.kind === 'adjustment' ? l.adjustment : l.payslip}<br>${escapeHtml(data.festival ?? periodName(data.language, data.periodStart, data.periodEnd))}</div></div>
<div class="grid">
<div><span>${l.employee}:</span> ${escapeHtml(data.employee.name)}</div>
<div><span>${l.code}:</span> ${escapeHtml(data.employee.code)}</div>
<div><span>${l.designation}:</span> ${escapeHtml(data.employee.designation ?? '—')}</div>
<div><span>${l.department}:</span> ${escapeHtml(data.employee.orgUnit ?? '—')}</div>
<div><span>${l.joined}:</span> ${date(data.language, data.employee.joinedOn)}</div>
<div><span>${l.paid}:</span> ${date(data.language, data.paymentDate)}</div>
</div>
${
  data.kind === 'bonus'
    ? ''
    : `<table class="days"><thead><tr><th>${l.periodDays}</th><th>${l.paidDays}</th><th>${l.absent}</th><th>${l.unpaidLeave}</th><th>${l.ot}</th></tr></thead>
<tbody><tr><td>${number(data.language, v.periodDays)}</td><td>${number(data.language, v.paidDays)}</td><td>${number(data.language, v.absentDays)}</td><td>${number(data.language, v.unpaidLeaveDays)}</td><td>${number(data.language, v.otHours)}</td></tr></tbody></table>`
}
<div class="cols">
<table><thead><tr><th>${l.earnings}</th><th class="num">${l.amount}</th></tr></thead><tbody>${rows('earning')}</tbody>
<tfoot><tr><td>${l.totalEarnings}</td><td class="num">${amountText(data.language, data.earnings)}</td></tr></tfoot></table>
<table><thead><tr><th>${l.deductions}</th><th class="num">${l.amount}</th></tr></thead><tbody>${rows('deduction')}</tbody>
<tfoot><tr><td>${l.totalDeductions}</td><td class="num">${amountText(data.language, data.deductions)}</td></tr></tfoot></table>
</div>
<div class="net"><span>${l.net}</span><span>${l.amount} ${amountText(data.language, data.net)}</span></div>
${words ? `<div class="words">${l.inWords}: ${escapeHtml(words)}</div>` : ''}
${data.settlement ? settlementSection(data.language, data.settlement) : ''}
<div class="note">${l.note}</div>`,
  );
}

/** A final settlement's working on its statement: how each due was counted. */
function settlementSection(language: 'en' | 'bn', w: SettlementWorking): string {
  const l = LABELS[language];
  const n = (v: number) => number(language, v);
  const rows: [string, string][] = [
    [l.lastDay, date(language, w.lastWorkingDay)],
    [l.service, l.serviceText(n(w.serviceYears), n(w.serviceMonths % 12))],
    [l.wage[w.wageBasis], `${l.amount} ${amountText(language, w.dailyWage)}`],
  ];
  if (w.notice.shortDays > 0) {
    rows.push([
      l.noticeShort,
      `${n(w.notice.shortDays)} ${l.daysUnit}: ${l.amount} ${amountText(language, w.notice.amount)}`,
    ]);
  }
  if (w.leave.days > 0) {
    rows.push([
      l.leaveDays,
      `${n(w.leave.days)} ${l.daysUnit} ${l.leaveRate(amountText(language, w.leave.dailyWage))}: ${l.amount} ${amountText(language, w.leave.amount)}`,
    ]);
  }
  for (const b of w.benefits) {
    rows.push([
      `${b.code === 'GRATUITY' ? l.gratuity : (l.benefit[w.type] ?? escapeHtml(b.label))} (${l.section(escapeHtml(b.reference))})`,
      `${l.slab(n(b.years), n(b.daysPerYear), amountText(language, b.dailyWage))}: ${l.amount} ${amountText(language, b.amount)}`,
    ]);
  }
  rows.push([l.dueBy, date(language, w.dueBy)]);
  const fund = w.providentFund
    ? `<table style="margin-top:10px"><thead><tr><th>${l.fund}</th><th class="num">${l.amount}</th></tr></thead><tbody>
<tr><td>${l.fundOwn}</td><td class="num">${amountText(language, w.providentFund.own)}</td></tr>
<tr><td>${l.fundEmployer}</td><td class="num">${amountText(language, w.providentFund.employer)}</td></tr></tbody>
<tfoot><tr><td>${l.amount}</td><td class="num">${amountText(language, w.providentFund.total)}</td></tr></tfoot></table>`
    : '';
  return `<table style="margin-top:14px"><tbody>${rows
    .map(([k, v]) => `<tr><td>${k}</td><td class="num">${v}</td></tr>`)
    .join('')}</tbody></table>${fund}`;
}
